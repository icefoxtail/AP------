import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const archiveDir = path.resolve(scriptDir, '../..');
const mapPath = path.join(archiveDir, 'data', 'question_identity_map.json');
const outputPath = path.join(archiveDir, 'question-identity.js');

function sha256(value) {
    return crypto.createHash('sha256').update(value).digest('hex');
}

if (!fs.existsSync(mapPath)) throw new Error(`identity map missing: ${mapPath}`);
const map = JSON.parse(fs.readFileSync(mapPath, 'utf8'));
if (map.schemaVersion !== 'question-identity-map-v1') throw new Error('question-identity-map-v1 is required');

const fileIndexByPath = {};
const files = [];
const byUid = {};
const byFile = {};
for (const record of map.records) {
    let fileIndex = fileIndexByPath[record.sourceArchiveFile];
    if (fileIndex === undefined) {
        fileIndex = files.length;
        fileIndexByPath[record.sourceArchiveFile] = fileIndex;
        files.push(record.sourceArchiveFile);
        byFile[String(fileIndex)] = { o: {}, n: {} };
    }
    byUid[record.questionUid] = [fileIndex, record.sourceOrdinal, record.sourceQuestionNo];
    byFile[String(fileIndex)].o[String(record.sourceOrdinal)] = record.questionUid;
    const byQuestionNo = byFile[String(fileIndex)].n;
    if (!byQuestionNo[record.sourceQuestionNo]) byQuestionNo[record.sourceQuestionNo] = [];
    byQuestionNo[record.sourceQuestionNo].push(record.questionUid);
}

const runtimeData = {
    schemaVersion: 'question-identity-runtime-v1',
    identityDigest: map.identityDigest,
    sourceCommit: map.sourceCommit,
    files,
    fileIndexByPath,
    byUid,
    byFile
};
const runtimeDigest = sha256(JSON.stringify(runtimeData));
const source = `// Generated by archive/tools/intelligence/build-question-identity-runtime.mjs\n// identityDigest: ${map.identityDigest}\n(function () {\n  const data = ${JSON.stringify({ ...runtimeData, runtimeDigest })};\n  function normalizeFile(value) { return String(value || '').normalize('NFC').replace(/\\\\/g, '/').replace(/^exams\\//, '').replace(/^\\.\\//, '').trim(); }\n  function positiveInteger(value) { const n = Number(value); return Number.isInteger(n) && n > 0 ? n : null; }\n  function pick(reference, names) { for (const name of names) { const value = reference && reference[name]; if (value !== undefined && value !== null && String(value).trim() !== '') return value; } return null; }\n  function unresolved(status, candidates) { return { status, questionUid: null, sourceArchiveFile: null, sourceOrdinal: null, sourceQuestionNo: null, candidates: candidates || [] }; }\n  function resolved(status, questionUid, tuple) { return { status, questionUid, sourceArchiveFile: data.files[tuple[0]], sourceOrdinal: tuple[1], sourceQuestionNo: tuple[2], candidates: [] }; }\n  window.questionIdentity = data;\n  window.resolveQuestionIdentityReference = function (reference) {\n    const questionUid = pick(reference, ['questionUid', 'question_uid', 'sourceQuestionUid', 'source_question_uid']);\n    if (questionUid) { const tuple = data.byUid[questionUid]; return tuple ? resolved('RESOLVED_CANONICAL_UID', questionUid, tuple) : unresolved('UNKNOWN_QUESTION_UID'); }\n    const sourceFile = normalizeFile(pick(reference, ['sourceArchiveFile', 'source_archive_file', 'sourceFile', '_sourceFile']) || '');\n    const sourceOrdinal = positiveInteger(pick(reference, ['sourceOrdinal', 'source_ordinal', 'sourceQuestionOrdinal', 'source_question_ordinal']));\n    const sourceQuestionNo = pick(reference, ['sourceQuestionNo', 'source_question_no', 'legacyQuestionNo', 'legacy_question_no', 'questionId', 'question_id', 'id']);\n    const fileIndex = data.fileIndexByPath[sourceFile];\n    const fileData = fileIndex === undefined ? null : data.byFile[String(fileIndex)];\n    if (sourceFile && sourceOrdinal) { const uid = fileData && fileData.o[String(sourceOrdinal)]; const tuple = uid && data.byUid[uid]; return tuple ? resolved('RESOLVED_SOURCE_ORDINAL', uid, tuple) : unresolved('UNKNOWN_SOURCE_ORDINAL'); }\n    if (sourceFile && sourceQuestionNo !== null) { const candidates = fileData && fileData.n[String(sourceQuestionNo)] || []; if (candidates.length === 1) return resolved('RESOLVED_LEGACY_UNAMBIGUOUS', candidates[0], data.byUid[candidates[0]]); if (candidates.length > 1) return unresolved('AMBIGUOUS_LEGACY_REFERENCE', candidates); return unresolved('UNKNOWN_LEGACY_REFERENCE'); }\n    return unresolved('INSUFFICIENT_IDENTITY_REFERENCE');\n  };\n})();\n`;

fs.writeFileSync(outputPath, source, 'utf8');
console.log(JSON.stringify({
    output: path.relative(path.resolve(archiveDir, '..'), outputPath).replace(/\\/g, '/'),
    identityDigest: map.identityDigest,
    runtimeDigest,
    fileCount: files.length,
    questionCount: map.records.length,
    bytes: Buffer.byteLength(source, 'utf8')
}, null, 2));
