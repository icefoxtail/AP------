import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const OUT = path.join(ROOT, 'archive', 'tools', 'logic-visual-audit', 'reports');
const generatedAtKst = '2026-09-06';
const sha = (value) => `sha256:${crypto.createHash('sha256').update(Buffer.isBuffer(value) ? value : typeof value === 'string' ? value : JSON.stringify(value)).digest('hex')}`;
const read = (name) => JSON.parse(fs.readFileSync(path.join(OUT, name), 'utf8'));
const write = (name, value) => fs.writeFileSync(path.join(OUT, name), JSON.stringify(value, null, 2) + '\n', 'utf8');

const inventory = read('phase2_2022_set_pilot_inventory.json');
const prior = new Set();
for (const file of fs.readdirSync(OUT).filter((name) => /^phase2_batch_\d+.*requirement_adjudication\.json$/.test(name) && name !== 'phase2_batch_11_requirement_adjudication.json')) {
  const report = read(file);
  for (const entry of report.entries ?? []) prior.add(entry.questionUid);
}
const remaining = inventory.rows.filter((row) => !prior.has(row.questionUid));
const sourceItems = remaining.map((row) => ({
  questionUid: row.questionUid,
  examId: row.examId,
  qid: row.qid,
  content: row.content,
  choices: row.choices,
  problemImageRefs: row.problemImageRefs,
  visibility: { answer: false, solution: false, solutionImage: false, solutionImageAlt: false, solutionImageCaption: false, builderMetadata: false, previousVerdict: false }
}));
const sourceBundle = {
  bundleType: 'V1_SOURCE_ONLY_LOGIC_VISUAL_PHASE2_BATCH_11',
  contractVersion: 'v2-independent-input-only',
  priorReviewVisibility: 'NONE',
  items: sourceItems,
  bundleSha: sha(sourceItems)
};
const artifactItems = remaining.map((row) => {
  const file = row.solutionImage ? path.join(ROOT, 'archive', row.solutionImage.replaceAll('/', path.sep)) : null;
  const bytes = file && fs.existsSync(file) ? fs.readFileSync(file) : null;
  return {
    questionUid: row.questionUid,
    artifactPath: row.solutionImage,
    artifactExists: Boolean(bytes),
    artifactSha256: bytes ? sha(bytes) : null,
    mimeType: row.solutionImage?.endsWith('.svg') ? 'image/svg+xml' : null,
    visibility: { question: false, choices: false, answer: false, solution: false, expectedFact: false, solutionImageAlt: false, solutionImageCaption: false, builderMetadata: false, previousVerdict: false }
  };
});
const artifactBundle = {
  bundleType: 'V2_ARTIFACT_ONLY_LOGIC_VISUAL_PHASE2_BATCH_11',
  contractVersion: 'v2-independent-input-only',
  priorReviewVisibility: 'NONE',
  items: artifactItems,
  bundleSha: sha(artifactItems)
};

write('phase2_batch_11_preparation_source_only.json', sourceBundle);
write('phase2_batch_11_preparation_artifact_only.json', artifactBundle);
