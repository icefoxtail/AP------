  inputCount: remaining.length,
  sourceBundle: 'phase2_batch_11_preparation_source_only.json',
  sourceBundleSha: sha(sourceBundle),
  artifactBundle: 'phase2_batch_11_preparation_artifact_only.json',
  artifactBundleSha: sha(artifactBundle),
  outputContract: 'This runner creates input bundles only. V1/V2 observations, requirement adjudication, typed parity, C freeze, item gate, and final PASS are forbidden here and must be produced by separate blind sessions.',
  legacyOutputsInvalidated: invalidatedLegacyOutputs.map((name) => ({ path: name, reason: 'Generated by the pre-hardening single-script path; not independent evidence.' })),
