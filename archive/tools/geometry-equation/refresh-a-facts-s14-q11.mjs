const sourcePath = path.join(staging, 'exams', qFact.sourceJsPath.replaceAll('/', path.sep));
const context = { window: {} };
vm.createContext(context);
vm.runInContext(fs.readFileSync(sourcePath, 'utf8'), context, { filename: sourcePath });
const question = context.window.questionBank.find((item) => item.id === qFact.id);
if (!question) throw new Error(`Question not found: ${qKey}`);
const clean = !/\[검수 메모\]|\[운영 메모\]|\[보강\]|TODO|FIXME|literal\s*\?|\?\?\?/.test(String(question.solution || ''));
