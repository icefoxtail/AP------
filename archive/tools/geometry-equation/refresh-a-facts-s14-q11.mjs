facts.releaseArtifactSha = release.releaseArtifactSha;
facts.refresh = { status: 'S14_Q11_FACT_REFRESH', source: 'a_independent_solve_facts_S6.json', qKey, q11Status: qFact.status, clean, previous, currentReleaseArtifactSha: release.releaseArtifactSha, targetCount: facts.facts.length };
