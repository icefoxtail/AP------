fs.writeFileSync(path.join(reports, 'a_facts_refresh_S14_q11.json'), JSON.stringify({ status: 'S14_Q11_FACT_REFRESHED', qKey, releaseArtifactSha: release.releaseArtifactSha, before: previous, after: { status: qFact.status, reasonCodes: qFact.reasonCodes, solutionIssues: qFact.solutionIssues }, sourceModified: false, solutionModified: false }, null, 2) + '\n', 'utf8');
console.log(JSON.stringify({ status: 'S14_Q11_FACT_REFRESHED', qKey, releaseArtifactSha: release.releaseArtifactSha, targetCount: facts.facts.length, passCount: facts.facts.filter((fact) => fact.status === 'PASS').length, repairRequiredCount: facts.facts.filter((fact) => fact.status !== 'PASS').length }, null, 2));
