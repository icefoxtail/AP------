import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const reports = path.join(root, 'reports', 'geometry_equation_20260902');
const staging = path.join(reports, 'staging', 'archive');
const production = path.join(root, 'archive');
const manifest = JSON.parse(fs.readFileSync(path.join(reports, 'geometry_equation_manifest.json'), 'utf8'));
const sha = (value) => crypto.createHash('sha256').update(value).digest('hex');

function loadWindow(filePath, key) {
  const context = { window: {} };
  vm.createContext(context);
  vm.runInContext(fs.readFileSync(filePath, 'utf8'), context, { filename: filePath });
  return context.window[key];
}

function stripHtml(value) {
  return String(value || '')
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&amp;/gi, '&')
    .replace(/&quot;/gi, '"')
    .replace(/&#39;/gi, "'")
    .replace(/\s+/g, ' ')
    .trim();
}

function questionMap(sourceJsPath) {
  const filePath = path.join(staging, 'exams', sourceJsPath.replaceAll('/', path.sep));
  const bank = loadWindow(filePath, 'questionBank') || [];
  return new Map(bank.map((question) => [`${sourceJsPath}_${question.id}`, question]));
}

const productionIndexPath = path.join(production, 'question-index.js');
const productionIndexText = fs.readFileSync(productionIndexPath, 'utf8');
const productionIndex = loadWindow(productionIndexPath, 'questionIndex') || [];
const indexByKey = new Map(productionIndex.map((record) => [record.qKey, record]));
const bankByFile = new Map();
const changes = [];

for (const row of manifest.rows) {
  if (!bankByFile.has(row.sourceJsPath)) bankByFile.set(row.sourceJsPath, questionMap(row.sourceJsPath));
  const question = bankByFile.get(row.sourceJsPath).get(row.qKey);
  const previous = indexByKey.get(row.qKey);
  if (!question || !previous) throw new Error(`Missing target in staging bank or production index: ${row.qKey}`);
  const next = {
    ...previous,
    standardUnit: question.standardUnit ?? previous.standardUnit,
    standardUnitKey: question.standardUnitKey ?? previous.standardUnitKey,
    subUnitKey: question.subUnitKey ?? previous.subUnitKey,
    subUnit: question.subUnit ?? previous.subUnit,
    subUnitConfidence: question.subUnitConfidence ?? previous.subUnitConfidence,
    subUnitClassificationDepth: question.subUnitClassificationDepth ?? previous.subUnitClassificationDepth,
    course: question.standardCourse ?? previous.course,
    level: question.level ?? previous.level,
    questionType: question.questionType ?? previous.questionType,
    tags: Array.isArray(question.tags) ? question.tags : previous.tags,
    hasImage: Boolean(question.image) || /<(?:img|svg|table)\b/i.test(String(question.content || '')),
    hasSolutionImage: Boolean(question.solutionImage),
    contentText: stripHtml(question.content),
    choicesText: Array.isArray(question.choices) ? question.choices.map(stripHtml).join(' ') : '',
  };
  const changedFields = Object.keys(next).filter((field) => JSON.stringify(previous[field] ?? null) !== JSON.stringify(next[field] ?? null));
  if (changedFields.length) changes.push({ qKey: row.qKey, sourceJsPath: row.sourceJsPath, id: row.id, changedFields, beforeHash: sha(JSON.stringify(previous)), afterHash: sha(JSON.stringify(next)) });
  indexByKey.set(row.qKey, next);
}

const nextIndex = productionIndex.map((record) => indexByKey.get(record.qKey) || record);
const nextText = `// Generated by geometry-equation target synchronization from production question-index\n// Target rows: ${manifest.rows.length}; non-target rows preserved byte-semantically as records.\nwindow.questionIndex=${JSON.stringify(nextIndex)};\n`;
fs.writeFileSync(path.join(staging, 'question-index.js'), nextText, 'utf8');
fs.writeFileSync(path.join(reports, 'staging_question_index_sync_S11.json'), JSON.stringify({ status: 'STAGING_INDEX_SYNCED_FROM_PRODUCTION_WITH_APPROVED_TARGETS', productionIndexSha256: sha(productionIndexText), stagingIndexSha256: sha(nextText), productionRecordCount: productionIndex.length, stagingRecordCount: nextIndex.length, targetCount: manifest.rows.length, changedTargetRecordCount: changes.length, changes }, null, 2) + '\n', 'utf8');
console.log(JSON.stringify({ status: 'STAGING_INDEX_SYNCED_FROM_PRODUCTION_WITH_APPROVED_TARGETS', productionRecordCount: productionIndex.length, stagingRecordCount: nextIndex.length, changedTargetRecordCount: changes.length, stagingIndexSha256: sha(nextText) }, null, 2));
