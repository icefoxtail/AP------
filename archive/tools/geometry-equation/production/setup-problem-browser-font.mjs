import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {bytesSha,fileRef} from '../../pipeline-core/canonical.mjs';
import {dependencyRoot,dependencyLock,dependency} from './dependencies.mjs';
import {extractFontNamePairs} from './font-name-table.mjs';
const root=fileURLToPath(new URL('../../../../',import.meta.url));
const source=path.join(dependencyRoot,'NotoSansKR.ttf'),bytes=fs.readFileSync(source);
if(bytesSha(bytes)!==dependencyLock.font.sha256)throw Error('BROWSER_FONT_HASH_LOCK_REQUIRED');
const font=dependency('opentype.js').parse(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength));
const sample='한글꼭짓점ㄱㄴ';
if([...sample].some(char=>font.charToGlyphIndex(char)===0))throw Error('BROWSER_FONT_KOREAN_GLYPH_MISSING');
const directory=path.join(os.homedir(),'.local/share/fonts/apmath-geometry');fs.mkdirSync(directory,{recursive:true});
const installed=path.join(directory,'NotoSansKR.ttf');fs.copyFileSync(source,installed);
if(bytesSha(fs.readFileSync(installed))!==dependencyLock.font.sha256)throw Error('BROWSER_FONT_INSTALL_HASH_MISMATCH');
execFileSync('fc-cache',['-f',directory],{stdio:'pipe'});
const family=execFileSync('fc-scan',['--format','%{family[0]}\n',installed],{encoding:'utf8'}).trim().split('\n')[0];
const matched=execFileSync('fc-match',['-f','%{file}\n',family],{encoding:'utf8'}).trim().split('\n')[0];
if(!family||bytesSha(fs.readFileSync(matched))!==dependencyLock.font.sha256)throw Error('BROWSER_FONT_FONTCONFIG_MISMATCH');
const output=path.join(root,'.tmp/svg-problem/browser-font.json');fs.mkdirSync(path.dirname(output),{recursive:true});
const fontSource='.tmp/svg-problem/browser-font-source.ttf';fs.writeFileSync(path.join(root,fontSource),bytes);
const evidence={status:'FONTCONFIG_HASH_VERIFIED',family,fontSha256:dependencyLock.font.sha256,fontSourceRef:fileRef(root,fontSource),nameTablePairs:extractFontNamePairs(bytes),installed,matched,koreanSample:sample,glyphCoverage:'ALL_PRESENT'};
fs.writeFileSync(output,JSON.stringify(evidence,null,2)+'\n');
console.log(JSON.stringify({status:evidence.status,family,fontSha256:evidence.fontSha256}));
