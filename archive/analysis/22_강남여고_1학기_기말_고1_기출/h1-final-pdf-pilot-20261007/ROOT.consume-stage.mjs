import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {buildStageState,consumeValidationPass} from '../../../tools/archive-stage-runtime-v2.mjs';
const [stage,reportFile,sessionId] = process.argv.slice(2);
const dir=path.dirname(fileURLToPath(import.meta.url));
const reportBytes=fs.readFileSync(reportFile), report=JSON.parse(reportBytes);
if(report.artifactContract?.questionCount!==24)throw Error('LOCKED_ARTIFACT_DENOMINATOR_MISMATCH');
if(stage!=='R3'&&(report.common?.observedQids?.length!==24||report.common?.expectedQids?.length!==24))throw Error('FULL_STAGE_DENOMINATOR_MISMATCH');
if(report.issues?.length||report.artifactContract?.issues?.length||!report.artifactContract?.active)throw Error('FULL_CURRENT_PASS_REQUIRED');
const stateFile=path.join(dir,'ROOT.state.json');
const prior=JSON.parse(fs.readFileSync(stateFile,'utf8'));
if(prior.stage!==stage)throw Error('STATE_STAGE_MISMATCH');
const consumed=consumeValidationPass({state:buildStageState({...prior,workComplete:true}),validationReport:report});
const event={at:new Date().toISOString(),type:'STAGE_COMPLETED_AND_ROUTED',examUid:report.examUid,stage,sessionId,artifactSha:report.artifactSha,report:{path:reportFile,sha256:createHash('sha256').update(reportBytes).digest('hex')},completedArtifactToNextStage:consumed.state.stage,freedSlot:stage,nextRosterTarget:null,consumer:consumed};
fs.writeFileSync(path.join(dir,'ROOT.'+stage+'.intake.json'),JSON.stringify(event,null,2)+'\n');
fs.writeFileSync(stateFile,JSON.stringify(consumed.state,null,2)+'\n');
console.log(JSON.stringify({ok:true,stage,nextStage:consumed.state.stage,artifactSha:report.artifactSha,questionCount:24}));
