import fs from 'node:fs';
import path from 'node:path';
import { readExam, physical, writeFresh } from '../../../tools/archive-codex-artifact-io.mjs';
import { STUDENT_FIELDS } from '../../../tools/archive-student-bundle.mjs';
const root=path.resolve(import.meta.dirname,'../../../..');
const examPath=path.join(root,'archive/exams/original/high/h2/1mid/24_매산여고_1학기_중간_고2_확률과통계.js');
const bundlePath=path.join(import.meta.dirname,'q22-student-only.bundle.json');
const freezePath=path.join(import.meta.dirname,'R2.q22-original-freeze.json');
const freeze=JSON.parse(fs.readFileSync(freezePath,'utf8'));
const bundle=JSON.parse(fs.readFileSync(bundlePath,'utf8'));
if(physical(freezePath).sha256!=='a131595fdd4fcca77998c20479a30d3ef491e86219919f2ca53d5ea1368bcc98') throw Error('FREEZE_SHA_MISMATCH');
if(freeze.sourceRawSha256!==bundle.sourceRawSha256||freeze.studentQidOrder.length!==1||freeze.studentQidOrder[0]!==22||freeze.rows.length!==1||freeze.rows[0].qid!==22) throw Error('Q22_FREEZE_SCOPE_MISMATCH');
const exam=readExam(examPath);
if(exam.rawSha256!==bundle.sourceRawSha256) throw Error('CURRENT_SOURCE_SHA_MISMATCH');
const q=exam.questions.find(x=>Number(x.id??x.qid)===22);
if(!q) throw Error('Q22_NOT_FOUND');
const student=Object.fromEntries([...STUDENT_FIELDS].filter(k=>Object.hasOwn(q,k)).map(k=>[k,q[k]]));
const saved=Object.fromEntries([...STUDENT_FIELDS].filter(k=>Object.hasOwn(bundle.rows[0].student,k)).map(k=>[k,bundle.rows[0].student[k]]));
if(JSON.stringify(student)!==JSON.stringify(saved)) throw Error('Q22_STUDENT_PARITY_MISMATCH');
const fields=['answer','solution','explanation','sol','solutionImage','solutionImageAlt','solutionImageCaption','solutionImageSize','decisiveStep'];
const disclosure={schemaVersion:'JS_ARCHIVE_Q22_POSTFREEZE_DISCLOSURE_V1',originalFreeze:physical(freezePath),studentBundle:physical(bundlePath),sourceRawSha256:exam.rawSha256,studentParity:'EXACT_QID_22',rows:[{qid:22,...Object.fromEntries(fields.filter(k=>Object.hasOwn(q,k)).map(k=>[k,q[k]]))}],disclosedAt:new Date().toISOString()};
const out=writeFresh(path.join(import.meta.dirname,'R2.q22-postfreeze-disclosure.json'),disclosure);
console.log(JSON.stringify({ref:out,studentParity:disclosure.studentParity,qid:22,fields:Object.keys(disclosure.rows[0]).filter(k=>k!=='qid')}));