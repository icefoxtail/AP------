import fs from 'node:fs';
import path from 'node:path';
import { readExam, sha256, inside, physical, writeFresh } from '../../../tools/archive-codex-artifact-io.mjs';
import { STUDENT_FIELDS, normalizeStudentBundle } from '../../../tools/archive-student-bundle.mjs';
const root=path.resolve(import.meta.dirname,'../../../..');
const sourceFile=path.join(root,'archive/exams/original/high/h2/1mid/24_매산여고_1학기_중간_고2_확률과통계.js');
const assetRoot=path.join(root,'archive');
const output=path.join(import.meta.dirname,'current-student-only.bundle.json');
const exam=readExam(sourceFile);
const rows=exam.questions.map(q=>{
 const qid=Number(q.id);
 const student=Object.fromEntries([...STUDENT_FIELDS].filter(k=>Object.hasOwn(q,k)).map(k=>[k,q[k]]));
 const refs=new Set();
 for(const v of [student.content,student.question,student.sharedContext,student.sharedMaterial,student.commonData,student.commonPassage,student.passage,student.table]) if(typeof v==='string') for(const m of v.matchAll(/<(?:img|image)\b[^>]*?(?:src|href|xlink:href)\s*=\s*["']([^"']+)/gi)) refs.add(m[1]);
 if(typeof student.image==='string') refs.add(student.image);
 const assets=[...refs].filter(r=>!/^(?:data:|#)/.test(r)).map(ref=>{const file=inside(assetRoot,ref);return {ref,path:file,sha256:sha256(fs.readFileSync(file))};});
 return {qid,student,assets};
});
const input={schemaVersion:'JS_ARCHIVE_SOURCE_STUDENT_PAYLOAD_V1',sourceRawSha256:exam.rawSha256,sourceRawBlobSha1:exam.rawBufferGitBlobSha1,questionCount:rows.length,qids:rows.map(r=>r.qid),rows};
const bundle=normalizeStudentBundle(input,{inputFile:sourceFile,expectedSourceRawSha256:exam.rawSha256});
const out=writeFresh(output,bundle);
console.log(JSON.stringify({...out,questionCount:bundle.questionCount,qids:bundle.qids,sourceRawSha256:exam.rawSha256,sourceRawBlobSha1:exam.rawBufferGitBlobSha1,assetRefs:rows.flatMap(r=>r.assets.map(a=>({qid:r.qid,ref:a.ref,sha256:a.sha256})))}));
