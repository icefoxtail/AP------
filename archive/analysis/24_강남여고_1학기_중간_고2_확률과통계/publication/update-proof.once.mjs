import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
const root = process.cwd();
const dirs = fs.readdirSync(path.join(root,'archive/analysis')).filter(n => n.startsWith('24_') && n.includes('강남') && n.includes('확률과통계'));
if (dirs.length !== 1) throw new Error(`UID_MATCHES:${dirs.join(',')}`);
const uid = dirs[0], base = path.join(root,'archive/analysis',uid), pub = path.join(base,'publication');
const sha = p => createHash('sha256').update(fs.readFileSync(path.join(root,p))).digest('hex');
const ap = path.join(pub,'registration-assignment.json'), pp = path.join(pub,'current-stage-proof-set.json');
const a = JSON.parse(fs.readFileSync(ap,'utf8')), proof = JSON.parse(fs.readFileSync(pp,'utf8'));
const ep = `archive/analysis/${uid}/r1/r1-stage-evidence-meta-dispositions.json`;
const rp = `archive/analysis/${uid}/r1/r1-generic-v2-report-meta-dispositions.json`;
const sp = `archive/analysis/${uid}/r1/r1-completion-seal-meta-dispositions.json`;
a.r1EvidencePath=ep; a.r1EvidenceSha256=sha(ep); a.r1EvidenceReferencePath=ep; a.r1ValidationPath=rp; a.r1ValidationSha256=sha(rp);
proof.proofs=proof.proofs.map(x=>x.stage==='R1'?{...x,path:ep,sha256:a.r1EvidenceSha256}:x);
proof.originalProofs=proof.originalProofs.filter(x=>!x.path.includes(`/${uid}/r1/`));
proof.originalProofs.push({path:rp,sha256:a.r1ValidationSha256},{path:sp,sha256:sha(sp)});
const pbytes=Buffer.from(JSON.stringify(proof,null,2)+'\n'); fs.writeFileSync(pp,pbytes);
a.currentStageProofManifestSha256=createHash('sha256').update(pbytes).digest('hex');
fs.writeFileSync(ap,JSON.stringify(a,null,2)+'\n');
console.log(JSON.stringify({uid,proofSha256:a.currentStageProofManifestSha256,r1EvidenceSha256:a.r1EvidenceSha256,r1ValidationSha256:a.r1ValidationSha256}));
