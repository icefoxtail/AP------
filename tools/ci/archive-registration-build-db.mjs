#!/usr/bin/env node
// Reuse generation only within one writer preparation. No registration,
// consumer, catalog, parity, or readiness verdict is cached by this module.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync, spawnSync} from 'node:child_process';
import {fileURLToPath, pathToFileURL} from 'node:url';

export const VERSION = 'archive-registration-build-db-checkpoint-v1';
const SELF = fileURLToPath(import.meta.url);
const COMMAND = ['python', 'archive/build_db.py'];
// These are the explicit read-only gates in the official build_db pipeline.
// Reusing generated bytes must not reuse their successful verdicts.
export const VALIDATION_COMMANDS = [
  ['node','archive/tools/build-basic-scope-parent-links.mjs','--check'],
  ['node','archive/tools/verify-archive-registration.mjs'],
  ['node','archive/tools/build-archive2-catalog.mjs','--check'],
  ['node','archive/tools/meta-foundation/refresh-runtime-source-readiness.mjs','--check']
];
// Variables a shell sets on its own (last command, nesting depth, previous directory): they differ between the bash scripts that
// call this wrapper and never change what the build writes.
const SHELL_VOLATILE_ENV = new Set(['_', 'SHLVL', 'OLDPWD']);
export const BYTE_BOUND_IGNORED_INPUTS = ['archive/data/question_metadata.json'];
const CACHE_FILE = 'build-db-checkpoint.json';
const EVENTS_FILE = 'build-db-events.jsonl';
const STATE = '.archive-meta-register/auto/writer-state.json';
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const stable = value => JSON.stringify(value, (_, v) => v && typeof v === 'object' && !Array.isArray(v)
  ? Object.fromEntries(Object.keys(v).sort().map(k => [k, v[k]])) : v);
const digest = value => sha(stable(value));
const inside = (child, parent) => child === parent || child.startsWith(parent + path.sep);
const splitZ = bytes => bytes.toString().split('\0').filter(Boolean);
const git = (root, env, args) => execFileSync('git', args, {cwd:root, env, maxBuffer:64*1024*1024,
  timeout:120000, stdio:['ignore','pipe','pipe']});
const text = (root, env, ...args) => git(root, env, args).toString().trim();
const assert = (condition, code) => { if (!condition) throw new Error(code); };

export function matches(file, patterns) {
  return patterns.some(p => p.endsWith('/') ? file.startsWith(p) : new RegExp('^' + p.split('*')
    .map(s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('.*') + '$').test(file));
}
function rowsDigest(rows) {
  return sha([...rows].sort((a,b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0)
    .map(r => `${r.path}\0${r.mode}\0${r.blob}\0${r.sha256||''}\0${r.bytes??''}\n`).join(''));
}
function worktreeRow(root, relative) {
  const file=path.join(root,relative);let initial;
  try { initial=fs.lstatSync(file); } catch(error) { if(error.code==='ENOENT')return null;throw error; }
  assert(initial.isFile() && !initial.isSymbolicLink(), 'CACHE_UNSUPPORTED_FILE_MODE');
  const raw=crypto.createHash('sha256'),blob=crypto.createHash('sha1').update(`blob ${initial.size}\0`);
  const fd=fs.openSync(file,'r'),buffer=Buffer.allocUnsafe(65536);let bytes=0;
  try { let n;while((n=fs.readSync(fd,buffer,0,buffer.length,null))>0){bytes+=n;raw.update(buffer.subarray(0,n));blob.update(buffer.subarray(0,n));} }
  finally { fs.closeSync(fd); }
  const final=fs.lstatSync(file);
  assert(bytes===initial.size && final.size===initial.size && final.mtimeMs===initial.mtimeMs
    && final.ino===initial.ino && final.mode===initial.mode,'CACHE_FILE_CHANGED_DURING_SNAPSHOT');
  return {path:relative,mode:(final.mode&0o111)!==0?'100755':'100644',blob:blob.digest('hex'),sha256:raw.digest('hex'),bytes};
}
function cacheLocation(root, env) {
  const id=env.ARCHIVE_REGISTRATION_BUILD_PREPARE_ID, value=env.ARCHIVE_REGISTRATION_BUILD_CACHE_DIR;
  if (!value && !id) return null;
  assert(typeof id==='string' && /^[a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12}$/.test(id), 'CACHE_PREPARE_ID_INVALID');
  assert(typeof value==='string' && path.isAbsolute(value), 'CACHE_DIRECTORY_NOT_ABSOLUTE');
  assert(!inside(path.resolve(value), root), 'CACHE_INSIDE_CHECKOUT');
  fs.mkdirSync(value, {recursive:true, mode:0o700});
  const dir=fs.realpathSync(value);
  assert(!inside(dir, fs.realpathSync(root)), 'CACHE_RESOLVES_INSIDE_CHECKOUT');
  assert(!fs.lstatSync(value).isSymbolicLink(), 'CACHE_DIRECTORY_IS_SYMLINK');
  return {dir, id, file:path.join(dir,CACHE_FILE), events:path.join(dir,EVENTS_FILE)};
}
async function productionPolicy(root) {
  const writer=await import(pathToFileURL(path.join(root,'tools/ci/archive-registration-writer.mjs')));
  return writer.nativeLanes(root);
}

// Hash raw current files, including unstaged producer output. Git clean filters
// and CRLF normalization cannot conceal a raw-byte change. The actual index,
// HEAD, refs, and files are never changed. All immutable tracked files outside
// the writer allowlist are also bound, including independent review documents.
export async function buildSnapshot({root, env=process.env, policyProvider=productionPolicy}) {
  const lanes=await policyProvider(root);
  assert(Array.isArray(lanes) && new Set(lanes.map(l=>l.id)).size===lanes.length, 'CACHE_LANE_POLICY_INVALID');
  const shared=lanes.find(l=>l.id==='shared');
  assert(shared && shared.enabled!==false && shared.required===true, 'CACHE_SHARED_LANE_REQUIRED');
  for(const lane of lanes) {
    assert(Array.isArray(lane.inputs) && Array.isArray(lane.outputs), 'CACHE_LANE_PATHS_INVALID');
    for(const p of [...lane.inputs,...lane.outputs,...(lane.scopedInputs||[])])
      assert(typeof p==='string' && p && !path.isAbsolute(p) && !p.split('/').includes('..'), 'CACHE_UNSAFE_POLICY_PATH');
  }
  const baseEnv={...env,GIT_NO_LAZY_FETCH:'1',GIT_OPTIONAL_LOCKS:'0'};
  assert(!['GIT_DIR','GIT_WORK_TREE','GIT_COMMON_DIR','GIT_INDEX_FILE'].some(k=>env[k]), 'CACHE_ALTERNATE_GIT_CONTEXT');
  assert(fs.realpathSync(text(root,baseEnv,'rev-parse','--show-toplevel'))===root,'CACHE_WRONG_GIT_WORKTREE');
  const head=text(root,baseEnv,'rev-parse','HEAD');
  assert(/^[a-f0-9]{40}$/.test(head), 'CACHE_HEAD_INVALID');
  const indexBytes=git(root,baseEnv,['ls-files','--stage','-z']);
  const indexRows=splitZ(indexBytes).map(row=>{
    const m=/^(\d+) ([a-f0-9]{40}) (\d)\t([\s\S]+)$/.exec(row);
    assert(m && m[3]==='0' && ['100644','100755'].includes(m[1]), 'CACHE_UNMERGED_OR_UNSUPPORTED_INDEX');
    return {path:m[4],mode:m[1],blob:m[2]};
  });
  const writerOutputs=[...new Set(lanes.flatMap(l=>l.outputs)),STATE];
  const dependencies=[...new Set([...shared.inputs,...shared.outputs])];
  const ignored=splitZ(git(root,baseEnv,['ls-files','--others','--ignored','--exclude-standard','-z']));
  // An ignored file the build reads cannot be bound by Git. The one exception is the assembled question metadata: the CI step
  // "Assemble question metadata" rebuilds it from tracked shards, and it is bound here by its raw bytes like any untracked
  // input (it is hashed into every snapshot below, so any change to it invalidates a checkpoint). Every other ignored dependency still refuses.
  const unboundIgnored=ignored.filter(p=>matches(p,dependencies)&&!BYTE_BOUND_IGNORED_INPUTS.includes(p));
  assert(unboundIgnored.length===0, 'CACHE_IGNORED_DEPENDENCY');
  const boundIgnored=ignored.filter(p=>BYTE_BOUND_IGNORED_INPUTS.includes(p)&&matches(p,dependencies));
  const names=[...new Set([...indexRows.map(r=>r.path),...splitZ(git(root,baseEnv,['ls-files','--others','--exclude-standard','-z'])),...boundIgnored])];
  const rows=names.map(p=>worktreeRow(root,p)).filter(Boolean);
  assert(sha(git(root,baseEnv,['ls-files','--stage','-z']))===sha(indexBytes),'CACHE_INDEX_CHANGED_DURING_SNAPSHOT');
  assert(text(root,baseEnv,'rev-parse','HEAD')===head, 'CACHE_HEAD_CHANGED_DURING_SNAPSHOT');
  const policy=lanes.map(l=>({id:l.id,enabled:l.enabled!==false,required:l.required===true,
    inputs:l.inputs,outputs:l.outputs,scopedInputs:l.scopedInputs||null,parameters:l.parameters||{}}));
  const python=JSON.parse(execFileSync(COMMAND[0],['-c','import json,sys; print(json.dumps({"executable":sys.executable,"version":sys.version,"prefix":sys.prefix,"basePrefix":sys.base_prefix}))'],
    {cwd:root,env,maxBuffer:16384,timeout:10000,stdio:['ignore','pipe','pipe']}).toString());
  const executableStat=p=>{const s=fs.statSync(p);return {size:s.size,mtimeMs:s.mtimeMs,ino:s.ino,dev:s.dev};};
  return {
    schemaVersion:VERSION, head, command:COMMAND,
    policySha256:digest(policy),
    sharedInputsSha256:digest({patterns:shared.inputs,parameters:shared.parameters||{},
      files:rowsDigest(rows.filter(r=>r.path!==STATE && matches(r.path,shared.inputs)))}),
    sharedOutputsSha256:rowsDigest(rows.filter(r=>r.path!==STATE && matches(r.path,shared.outputs))),
    immutableOutsideWriterSha256:rowsDigest(rows.filter(r=>!matches(r.path,writerOutputs))),
    immutableIndexSha256:rowsDigest(indexRows.filter(r=>!matches(r.path,writerOutputs))),
    trackedDependencyPathsSha256:digest(indexRows.filter(r=>matches(r.path,dependencies)).map(r=>[r.path,r.mode])),
    gitReferencesSha256:sha(git(root,baseEnv,['for-each-ref','--format=%(refname)%00%(objectname)'])),
    gitConfigurationSha256:sha(git(root,baseEnv,['config','--null','--list','--show-origin'])),
    environmentSha256:digest(Object.fromEntries(Object.entries(env).filter(([k])=>!SHELL_VOLATILE_ENV.has(k)))),
    nodeExecutable:process.execPath,nodeVersion:process.version,nodeExecutableStat:executableStat(process.execPath),
    python,pythonExecutableStat:executableStat(python.executable),wrapperSha256:sha(fs.readFileSync(SELF)),
    files:rows.length
  };
}
function checkpoint(location, snapshot) {
  try {
    const stat=fs.lstatSync(location.file);
    if(!stat.isFile() || stat.isSymbolicLink() || (stat.mode&0o022)!==0 || stat.size>16384)return false;
    const c=JSON.parse(fs.readFileSync(location.file,'utf8'));
    const keys=['schemaVersion','prepareId','command','exitCode','signal','snapshot','snapshotSha256'];
    if(stable(Object.keys(c).sort())!==stable(keys.sort()))return false;
    return c.schemaVersion===VERSION && c.prepareId===location.id && stable(c.command)===stable(COMMAND)
      && c.exitCode===0 && c.signal===null && c.snapshotSha256===digest(c.snapshot)
      && stable(c.snapshot)===stable(snapshot);
  } catch { return false; }
}
function invalidate(location) {
  if(!location)return;
  try { fs.rmSync(location.file,{force:true}); } catch { /* Never reuse it after any failed check. */ }
}
function event(location, value) {
  if(location) {
    if(fs.existsSync(location.events)) {
      const stat=fs.lstatSync(location.events);
      assert(stat.isFile() && !stat.isSymbolicLink() && (stat.mode&0o022)===0,'CACHE_UNSAFE_EVENT_FILE');
    }
    fs.appendFileSync(location.events,JSON.stringify(value)+'\n',{mode:0o600});
  }
}
function generatedResult(result) {
  return {status:result.status,signal:result.signal??null,error:result.error?String(result.error.code||'BUILD_PROCESS_ERROR'):null};
}

export async function runBuildDb({root=process.cwd(), env=process.env, policyProvider=productionPolicy,
  executeBuild=()=>spawnSync(COMMAND[0],COMMAND.slice(1),{cwd:root,env,stdio:'inherit'}),
  executeValidation=command=>spawnSync(command[0],command.slice(1),{cwd:root,env,stdio:'inherit'}), log=console.log}={}) {
  root=fs.realpathSync(root);
  let location=null, before=null, cacheUnavailableCode=null;
  try {
    location=cacheLocation(root,env);
    if(location)before=await buildSnapshot({root,env,policyProvider});
  } catch(error) { cacheUnavailableCode=/^CACHE_[A-Z_]+$/.test(error.message)?error.message:'CACHE_SNAPSHOT_UNAVAILABLE'; }
  if(location && before && checkpoint(location,before)) {
    const checks=[];
    try {
      for(const command of VALIDATION_COMMANDS) {
        const check=generatedResult(executeValidation(command));checks.push({command,...check});
        assert(check.status===0 && check.signal===null && check.error===null,'CACHE_FRESH_VALIDATION_FAILED');
      }
      const checked=await buildSnapshot({root,env,policyProvider});
      assert(stable(checked)===stable(before),'CACHE_FRESH_VALIDATION_MUTATED_INPUT');
      const result={schemaVersion:VERSION,status:'GENERATION_REUSED',prepareId:location.id,head:before.head,
        snapshotSha256:digest(before),command:COMMAND,generationExecuted:false,validationSkipped:false,
        freshValidationCommands:checks,registrationApprovalClaim:false,exitCode:0,signal:null};
      event(location,result);log(JSON.stringify(result));return result;
    } catch(error) {
      cacheUnavailableCode=/^CACHE_[A-Z_]+$/.test(error.message)?error.message:'CACHE_REUSE_EVENT_UNAVAILABLE';
      try { event(location,{schemaVersion:VERSION,status:'REUSE_REFUSED_REGENERATING',prepareId:location.id,
        head:before.head,reason:cacheUnavailableCode,freshValidationCommands:checks}); } catch { /* Real generation follows. */ }
      // The rejected checks may have changed files. Do not bind the fallback
      // producer to the earlier snapshot or certify its outputs as reusable.
      before=null;
    }
  }
  invalidate(location);
  const started=Date.now();
  const processResult=generatedResult(executeBuild());
  const success=processResult.status===0 && processResult.signal===null && processResult.error===null;
  let saved=false, after=null;
  if(success && location && before)try {
    after=await buildSnapshot({root,env,policyProvider});
    // The generator reads some of its own outputs. A successful first pass is
    // not evidence that generation on the resulting read set is a fixed point.
    // Only seal the exact inputs and execution context that this run consumed.
    assert(after.sharedInputsSha256===before.sharedInputsSha256,'CACHE_GENERATION_INPUT_CHANGED');
    const context=s=>Object.fromEntries(Object.entries(s).filter(([k])=>
      k!=='sharedOutputsSha256'&&k!=='files'));
    assert(stable(context(after))===stable(context(before)), 'CACHE_IMMUTABLE_CONTEXT_CHANGED');
    const data={schemaVersion:VERSION,prepareId:location.id,command:COMMAND,exitCode:0,signal:null,
      snapshot:after,snapshotSha256:digest(after)};
    const temporary=location.file+'.'+crypto.randomUUID()+'.tmp';
    try {
      fs.writeFileSync(temporary,JSON.stringify(data)+'\n',{mode:0o600,flag:'wx'});
      fs.renameSync(temporary,location.file);saved=true;
    } finally { fs.rmSync(temporary,{force:true}); }
  } catch(error) { cacheUnavailableCode=/^CACHE_[A-Z_]+$/.test(error.message)?error.message:'CACHE_POST_SNAPSHOT_UNAVAILABLE';invalidate(location); }
  const result={schemaVersion:VERSION,status:success?'GENERATED':'GENERATION_FAILED',prepareId:location?.id??null,
    head:after?.head??before?.head??null,command:COMMAND,generationExecuted:true,validationSkipped:false,
    registrationApprovalClaim:false,checkpointSaved:saved,cacheUnavailableCode,elapsedMs:Date.now()-started,
    exitCode:processResult.status,signal:processResult.signal,processErrorCode:processResult.error};
  try { event(location,result); } catch { /* A successful generation is still required by all existing validators. */ }
  log(JSON.stringify(result));return result;
}
if(process.argv[1] && path.resolve(process.argv[1])===SELF) {
  if(process.argv.length!==2)throw Error('BUILD_DB_WRAPPER_TAKES_NO_ARGUMENTS');
  const result=await runBuildDb();process.exitCode=result.exitCode===0&&result.signal===null?0:result.exitCode||1;
}
