def clean_and_save(src_path, dst_path, thresh=215, padding=16):
    img = cv2.imdecode(np.fromfile(src_path, dtype=np.uint8), cv2.IMREAD_COLOR)
    if img is None:
        raise FileNotFoundError(f"Source image not found: {src_path}")
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    mask_bg = gray > thresh
    result = img.copy()
    result[mask_bg] = [255, 255, 255]
    
    if padding > 0:
        h, w, c = result.shape
        padded = np.full((h + 2*padding, w + 2*padding, c), 255, dtype=np.uint8)
        padded[padding:padding+h, padding:padding+w] = result
        result = padded
        
    os.makedirs(os.path.dirname(dst_path), exist_ok=True)
    ext = os.path.splitext(dst_path)[1]
    is_success, buf = cv2.imencode(ext, result)
    if is_success:
        buf.tofile(dst_path)
        print(f"Normalized asset saved: {dst_path}")
    else:
        raise RuntimeError(f"Failed to encode: {dst_path}")

