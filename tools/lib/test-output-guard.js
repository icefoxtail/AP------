'use strict';
// Puts back the committed files that the test runner's pre-step regenerates,
// without ever touching anything else in the working tree.
//
// Why: between a source-changing merge and the post-merge "sync registration
// artifacts" bot commit, the committed Archive2 canonical artifacts are stale,
// so tools/run-tests.js (whose pre-step rebuilds them) used to leave a dirty
// tree that could be committed by mistake. Someone else (a person or another
// worker) may edit the same working tree during the 6-7 minute run, so the
// guard restores only a file that
//   1. is one of the pre-step's known output paths,
//   2. was clean before the run, and
//   3. still has exactly the content the pre-step wrote (nobody touched it).
// Every other newly changed tracked file is only reported.
const { spawnSync } = require('child_process');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

function sha(file) {
  try {
    return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
  } catch {
    return null; // missing
  }
}

function createOutputGuard({ root, outputFiles, outputPrefixes, keep = false, log = console.log }) {
  const isPrestepOutput = (file) =>
    outputFiles.includes(file) || outputPrefixes.some((prefix) => file.startsWith(prefix));

  function dirtyPaths() {
    const out = spawnSync('git', ['status', '--porcelain', '-z', '--untracked-files=all'], {
      cwd: root,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024
    });
    if (out.status !== 0 || out.error) return null;
    const entries = new Map();
    const parts = out.stdout.split('\0').filter(Boolean);
    for (let i = 0; i < parts.length; i += 1) {
      const code = parts[i].slice(0, 2);
      entries.set(parts[i].slice(3), code);
      if (code[0] === 'R' || code[0] === 'C') i += 1;
    }
    return entries;
  }

  let before = null;
  const candidates = new Map(); // path -> sha256 of what the pre-step wrote
  let finished = false;

  return {
    begin() {
      if (keep) return;
      before = dirtyPaths();
      if (before) {
        log('Catalog artifacts regenerated by the test run are put back afterwards; '
          + 'set APMATH_KEEP_TEST_OUTPUT=1 to keep them for a commit.');
      }
    },
    // Call right after the pre-step (even when it failed).
    afterPrestep() {
      if (keep || !before) return;
      const now = dirtyPaths();
      if (!now) return;
      for (const [file, code] of now) {
        if (code === '??' || before.has(file) || !isPrestepOutput(file)) continue;
        candidates.set(file, sha(path.join(root, file)));
      }
    },
    finish() {
      if (finished || keep || !before) return;
      finished = true;
      const after = dirtyPaths();
      if (!after) return;
      const restore = [];
      for (const [file, expected] of candidates) {
        if (sha(path.join(root, file)) === expected) restore.push(file);
        else log(`NOT_RESTORED ${file} (changed during run)`);
      }
      if (restore.length > 0) {
        const result = spawnSync('git', ['checkout', '--', ...restore], { cwd: root, stdio: 'inherit' });
        for (const file of restore) {
          log(result.status === 0 ? `RESTORED ${file}` : `NOT_RESTORED ${file} (git checkout failed)`);
        }
      }
      for (const [file, code] of after) {
        if (before.has(file) || candidates.has(file)) continue;
        log(code === '??' ? `UNTRACKED ${file}` : `CHANGED_DURING_RUN ${file}`);
      }
    }
  };
}

module.exports = { createOutputGuard };
