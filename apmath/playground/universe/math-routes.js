export function getLabsByGrade(gradeKey) {
  if (!gradeKey || gradeKey === 'all') return MATH_LAB_REGISTRY;
  return MATH_LAB_REGISTRY.filter(lab => lab.courseKey === gradeKey);
}

export function getLabsByCelestial(celestialId) {
  if (!celestialId) return MATH_LAB_REGISTRY;
  return MATH_LAB_REGISTRY.filter(lab => lab.celestialId === celestialId);
}

export function searchLabs(query) {
  if (!query) return MATH_LAB_REGISTRY;
  const q = query.toLowerCase().trim();
  return MATH_LAB_REGISTRY.filter(lab => {
    return (
      (lab.title && lab.title.toLowerCase().includes(q)) ||
      (lab.keywords && lab.keywords.toLowerCase().includes(q)) ||
      (lab.category && lab.category.toLowerCase().includes(q)) ||
      (lab.unit && lab.unit.toLowerCase().includes(q)) ||
      (lab.formula && lab.formula.toLowerCase().includes(q)) ||
      (lab.summary && lab.summary.toLowerCase().includes(q))
    );
  });
}
