const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const test = require('node:test');

const workflow = fs.readFileSync(path.join(__dirname, '../.github/workflows/archive-registration-sync.yml'), 'utf8');
function script(name) {
  const section = workflow.split(`      - name: ${name}\n`)[1]?.split('\n      - ')[0];
  assert.ok(section, `workflow step ${name}`);
  const body = section.split('        run: |\n')[1];
  assert.ok(body, `workflow shell ${name}`);
  return body.split('\n').map(line => line.replace(/^          /, '')).join('\n');
}
function run(cwd, command, args, env = {}) {
  return spawnSync(command, args, { cwd, encoding: 'utf8', env: { ...process.env, ...env } });
}
function ok(cwd, command, args, env) {
  const result = run(cwd, command, args, env);
  assert.equal(result.status, 0, result.stdout + result.stderr);
  return result.stdout.trim();
}
function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'archive-readonly-preview-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const repo = path.join(root, 'repo'), temp = path.join(root, 'temp'), remote = path.join(root, 'remote.git');
  fs.mkdirSync(repo); fs.mkdirSync(temp);
  ok(repo, 'git', ['init', '-q', '--initial-branch=main']);
  for (const [key, value] of [['user.name', 'fixture'], ['user.email', 'fixture@example.invalid'], ['commit.gpgsign', 'false']]) {
    ok(repo, 'git', ['config', key, value]);
  }
  fs.mkdirSync(path.join(repo, 'archive/data'), { recursive: true });
  fs.writeFileSync(path.join(repo, 'archive/db.js'), 'const db = [];\n');
  const source = path.join(repo, 'archive/student-source.js');
  const sourceBytes = 'const student = 1;\n';
  fs.writeFileSync(source, sourceBytes);
  ok(repo, 'git', ['add', '--', 'archive']);
  ok(repo, 'git', ['commit', '-qm', 'fixture baseline']);
  ok(root, 'git', ['init', '--bare', '-q', remote]);
  ok(repo, 'git', ['remote', 'add', 'origin', remote]);
  ok(repo, 'git', ['push', '-q', 'origin', 'HEAD:refs/heads/main']);
  const head = ok(repo, 'git', ['rev-parse', 'HEAD']);
  const remoteRefs = ok(repo, 'git', ['ls-remote', '--refs', 'origin']);
  const env = { RUNNER_TEMP: temp, GITHUB_OUTPUT: path.join(temp, 'output'), GITHUB_STEP_SUMMARY: path.join(temp, 'summary'), PR_HEAD_SHA: head };
  const preview = path.join(temp, 'registration-preview');
  const checkUnchangedRefs = () => {
    assert.equal(ok(repo, 'git', ['rev-parse', 'HEAD']), head);
    assert.equal(ok(repo, 'git', ['rev-list', '--count', 'HEAD']), '1');
    assert.equal(ok(repo, 'git', ['ls-remote', '--refs', 'origin']), remoteRefs);
  };
  return { repo, temp, head, env, root, preview, source, sourceBytes, checkUnchangedRefs };
}
const previewScript = () => `${script('Guard generated scope')}\n${script('Record the read-only registration preview')}`;

test('read-only PR preview preserves tracked/new generated bytes and snapshot identity without a main repair writer', t => {
  const f = fixture(t);
  assert.doesNotMatch(workflow, /^  repair:|Apply the exact verified registration preview|create-pull-request|git apply --index/m);
  assert.doesNotMatch(workflow, /git commit|git push|contents: write|pull-requests: write/);
  const generated = 'const db = ["fixture"];\n', metadata = '{"fixture":true}\n';
  fs.writeFileSync(path.join(f.repo, 'archive/db.js'), generated);
  fs.writeFileSync(path.join(f.repo, 'archive/data/question_metadata.json'), metadata);
  ok(f.repo, 'bash', ['-c', previewScript()], f.env);
  f.checkUnchangedRefs();
  assert.equal(fs.readFileSync(f.source, 'utf8'), f.sourceBytes);
  assert.equal(fs.readFileSync(path.join(f.repo, 'archive/db.js'), 'utf8'), generated);
  assert.equal(fs.readFileSync(path.join(f.repo, 'archive/data/question_metadata.json'), 'utf8'), metadata);
  assert.deepEqual(fs.readdirSync(f.preview).sort(), ['registration.patch', 'source.sha']);
  const patchFile = path.join(f.preview, 'registration.patch');
  const patch = fs.readFileSync(patchFile, 'utf8');
  assert.match(patch, /diff --git a\/archive\/db\.js b\/archive\/db\.js/);
  assert.match(patch, /diff --git a\/archive\/data\/question_metadata\.json b\/archive\/data\/question_metadata\.json\nnew file mode 100644/);
  assert.ok(patch.includes(`+${generated.trim()}`));
  assert.ok(patch.includes(`+${metadata.trim()}`));
  assert.doesNotMatch(patch, /student-source/);
  // Parse the emitted patch without applying it or recreating the retired repair path.
  const paths = ok(f.repo, 'git', ['apply', '--numstat', patchFile]).split('\n').map(line => line.split('\t').at(-1)).sort();
  assert.deepEqual(paths, ['archive/data/question_metadata.json', 'archive/db.js']);
  assert.equal(fs.readFileSync(path.join(f.preview, 'source.sha'), 'utf8').trim(), f.head);
  assert.match(fs.readFileSync(f.env.GITHUB_OUTPUT, 'utf8'), new RegExp(`^source_sha=${f.head}$`, 'm'));
  assert.match(fs.readFileSync(f.env.GITHUB_STEP_SUMMARY, 'utf8'), /Remote writes: none/);
});

test('actual PR guard rejects unstaged, staged and newly added source mutations before preview publication', t => {
  const f = fixture(t);
  for (const [name, file, staged] of [
    ['tracked unstaged', f.source, false], ['tracked staged', f.source, true],
    ['new untracked', path.join(f.repo, 'archive/new-source.js'), false],
    ['new staged', path.join(f.repo, 'archive/new-source.js'), true],
  ]) {
    ok(f.repo, 'git', ['reset', '--hard', 'HEAD']);
    ok(f.repo, 'git', ['clean', '-fd', '--', 'archive']);
    fs.rmSync(f.preview, { recursive: true, force: true });
    const mutation = `const unauthorizedFixture = ${JSON.stringify(name)};\n`;
    fs.writeFileSync(file, mutation);
    if (staged) ok(f.repo, 'git', ['add', '--', file]);
    const result = run(f.repo, 'bash', ['-c', previewScript()], f.env);
    assert.notEqual(result.status, 0, `${name} source must not pass`);
    assert.match(result.stdout + result.stderr, /Unexpected generated file:/);
    assert.equal(fs.existsSync(f.preview), false, 'failed guard cannot create a successful preview artifact');
    assert.equal(fs.readFileSync(file, 'utf8'), mutation, 'guard must not overwrite the rejected input');
    f.checkUnchangedRefs();
  }
});
